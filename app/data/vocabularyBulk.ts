const parseWordSeeds = (data: string): WordSeed[] => data.split('\n').map((line) => line.split('|') as unknown as WordSeed)

const parseNounSeeds = (data: string): NounSeed[] => {
  const seen = new Set<string>()
  const coreWords = new Set(['книга', 'семья', 'вода'])

  return data.split('\n')
    .map((line) => line.split('|'))
    .filter(([word]) => {
      if (!word || coreWords.has(word) || seen.has(word)) return false
      seen.add(word)
      return true
    })
    .map(([word, stressedWord, meaning, gender, plural, animate]) => [
      word!, stressedWord!, meaning!, gender as NounSeed[3], plural!, animate === '1',
    ])
}

let nextNumber = 6
const nextId = () => `vocab-${String(nextNumber++).padStart(3, '0')}`

const nounItems = parseNounSeeds(nounData).map((seed) => makeNoun(nextId(), seed))
const verbItems = parseWordSeeds(verbData)
  .filter(([word]) => word !== 'читать' && word !== 'следовать' && word !== 'существовать')
  .map((seed) => makeVerb(nextId(), seed))
const adjectiveItems = parseWordSeeds(adjectiveData)
  .filter(([word]) => word !== 'новый')
  .map((seed) => makeAdjective(nextId(), seed))
const simpleItems = simpleData.flatMap(({ partOfSpeech, data }) =>
  parseWordSeeds(data).map((seed) => makeSimple(nextId(), seed, partOfSpeech)),
)

export const bulkVocabularyItems: VocabularyItem[] = [
  ...nounItems,
  ...verbItems,
  ...adjectiveItems,
  ...simpleItems,
]

if (bulkVocabularyItems.length !== 545) {
  throw new Error(`Vocabulary pool must contain 545 bulk items, got ${bulkVocabularyItems.length}`)
}
